"""二值化（固定阈值 / 大津 Otsu）与形态学（腐蚀/膨胀/开/闭）。

对应主仓库：
- 二值化 + 连通域面积过滤 = 监督 eval 的"概率图 > threshold -> mask -> 组件统计"；
- 形态学闭运算 = 无监督 eval 输出二值 mask 后 MORPH_CLOSE(15,15) 的碎片粘合。

核心直觉（背下来）：
- 腐蚀：白区收缩（窗口内只要有一个黑，中心变黑）；膨胀：白区扩张。
- 开 = 先腐蚀再膨胀：去掉比结构元小的白点（椒噪声），大块基本还原。
- 闭 = 先膨胀再腐蚀：填掉比结构元小的黑洞，大块基本还原。

★ 上面的"白/黑"指什么（最常见的误会）：形态学只认二值 mask，mask 上的约定是
  "白 = 目标、黑 = 背景"——与目标在灰度图里原本是亮是暗无关。划痕偏亮、砂眼偏
  暗，这个差别在二值化那一步就消化掉了：二值化是"翻译器"，亮的缺陷用正相阈值、
  暗的缺陷用 THRESH_BINARY_INV（inverse=True），翻出来目标一律是白（一张图同时
  有亮暗缺陷就分两条通路各翻各的，最后合并）。于是下游的开/闭（只懂白黑的
  "清洁工"）分工是：
- 开：清掉"白里的假货"——mask 上孤立的、小的白色斑块（噪声过阈值、模型零星
  误报）；
- 闭：补上"白里的破洞"——目标内部被切漏的小窟窿、同一目标断成几片留下的黑缝。
  两类残渣哪条通路都会有，所以常"先开后闭"一条龙。真正要提前确认的（都不是
  "目标黑还是白"）：
  1) 极性拨对没有——mask 里目标是白的吗？（拨反了，闭会把小的真缺陷当小黑洞补
     掉，真缺陷凭空消失）
  2) 尺寸分不分得开——假小白斑要明显小于最小真目标（否则开会把真目标一起删），
     闭的核别大到把挨得近的两个真目标粘成一个。

运行：python -m stage1.threshold_morphology
"""

import cv2
import numpy as np
from numpy.lib.stride_tricks import sliding_window_view


def binarize_fixed(gray: np.ndarray, threshold: int) -> np.ndarray:
    """固定阈值二值化：拿一条写死的分数线逐像素判"过线没有"——过线记 255（白）、
    没过记 0（黑）。输出只剩这两种值，所以叫"二值化"。
    "固定"是相对 binarize_otsu 而言：线是你当参数传进来的常数，与图像内容无关。

    ★ 严格大于：正好等于 threshold 的像素算"没过线"。测试同款手算：
        [[10, 100], [200, 250]]，threshold=100  ->  [[0, 0], [255, 255]]
        100 没到"大于 100"所以是黑的，只有 200、250 过了线。

    ★ 为什么写成 _, binary =：cv2.threshold 固定返回 (实际用到的阈值, 结果图)。
      固定阈值时第一个值就是你传进去的数、原样返回没有新信息，用 _ 扔掉；对照
      binarize_otsu——那里第一个值是 Otsu 自己算出来的阈值，有信息量，所以返回了。

    工程定位：主仓库监督 eval 的"概率图 > threshold -> mask -> 连通域统计"里，
    这一步就是其中的二值化；threshold 是判"算不算缺陷"的门槛，过线算前景。
    """
    # cv2.threshold(输入图, 分数线, 过线写什么值=255 白, 规则: >threshold 为白否则黑)
    _, binary = cv2.threshold(gray, threshold, 255, cv2.THRESH_BINARY)
    return binary


def binarize_otsu(gray: np.ndarray, inverse: bool = False) -> tuple:
    """大津法自动选阈值（Otsu 1979）：把 0~255 所有候选线试一遍，挑"把像素分成
    两堆后分得最开"的那条 = 类间方差最大的分割点；双峰直方图下就是站到谷底。

    ★ "分得最开"怎么算（候选线 t 把像素切成 ≤t 和 >t 两堆）：
        分数 = w0 × w1 × (μ0 − μ1)²      w = 两堆占比，μ = 两堆均值
      小直方图手算（3 个像素 = 10，6 个像素 = 100）：
        t 落在两群之间任意位置（10~99）-> 两堆纯（10 对 100）
          -> 0.33 × 0.67 × 90² = 1800（最大）
        t 挪出群外（t=100）-> 有一堆为空 -> 0
      线站谷底两堆才纯、均值差最大；切进某一群内部则两堆混着相似的值，分数变小。

    ★ 为什么不能用写死的（实测：背景 ~120、缺陷 ~40，真值缺陷占 7.3%）：
      整图亮度 -30 模拟光照漂过后，固定阈值 100 判"暗"的面积从 8.2% 膨胀到
      92.4%——背景跌到 90 被全判成缺陷，大面积误报；Otsu 的线从 71 跟着下移到
      41，判"暗"仍 7.3%，照样站在谷底。

    ★ thresh 传 0 只是占位符：加了 | cv2.THRESH_OTSU 后 OpenCV 不用你传的数、
      自己算，算出的线放在返回值第一个位置（demo 里 = 71.0）——这正是
      binarize_fixed 里被 _ 扔掉的那个位置，那边原样返回没信息，这边是主角。

    inverse=True 用 THRESH_BINARY_INV 把规则反过来（≤t 记白）：默认约定"亮 = 白
    = 前景"，想让暗的缺陷变成白色前景时用。返回 (threshold, binary)。
    边界：只对双峰直方图靠谱；单峰没有谷底可站，选出来的线没有意义。
    """
    flag = cv2.THRESH_BINARY_INV if inverse else cv2.THRESH_BINARY
    # thresh 传 0 只是占位：带 OTSU 标志时 cv2 忽略它，自己算线放进返回值 thr
    thr, binary = cv2.threshold(gray, 0, 255, flag | cv2.THRESH_OTSU)
    return thr, binary


def erode_manual(binary: np.ndarray, ksize: int = 3) -> np.ndarray:
    """手写腐蚀 = 最小值滤波（窗口全白才白）：每个像素换成它 k×k 邻域里的最小值。

    白=255、黑=0，所以"框里有一个黑，中心就变黑"——白区从边界往里缩，像被酸啃
    掉外圈：ksize=3（半径 1）一次啃掉 1 像素厚的一圈，比窗口小的白点直接消失。
    仅教学用：内部区域与 cv2 一致（边界差异见下），对拍通过后放心用 cv2.erode。

    ★ 一维手算（把图当成 1 行；窗口 = 自己 + 左右各 1 个）：
        原始 4 个白:     [255, 255, 255, 255]
        两边各补 1 个 0: [0, 255, 255, 255, 255, 0]      <- pad 出来的"图外=黑"
        4 张窗口取 min（框里有 0 就是 0，全白才 255）：
          [ 0 ,255,255] -> 0    |  [255,255,255] -> 255
          [255,255,255] -> 255  |  [255,255, 0 ] -> 0
        结果 [0, 255, 255, 0]：白色段两端各缩 1（4 个白 -> 2 个白）。输出仍是 4 个
        数：补 2 个后 6 个数里 3 窗口只能摆 6-3+1 = 4 个位置。
      2D 就是放大版：窗口从 3 个数变成 3×3 = 9 个数（自己 + 周围一圈）。demo 实测：
      30×30 白方块（900 px）-> 28×28（784 px），四边各缩 1。

    ★ 与 cv2.erode 的唯一差异（实测 5×5 全白图）：手写版外圈被啃成黑、只剩中间
      3×3 白；cv2 全白不动——手写版把图外当黑补进来，cv2 默认腐蚀时图外不参与
      （等效 +∞，永远赢不了 min）。所以"仅内部区域与 cv2 一致"，demo 和测试都只
      对拍内部 slice(2,-2)。

    定位：排序统计滤波家族（中值滤波取排序正中、腐蚀取最小）；开运算的前半段
    （腐蚀 -> 膨胀 = 开）；膨胀版 dilate_manual 就是 min 换成 max 的镜像。
    """
    r = ksize // 2                       # 邻域半径 r：ksize=3 -> r=1，看自己 ±1 一圈
    # 图外补 r 圈 0（当黑）：补出完整邻域，也让输出尺寸不变（见上面的一维手算）
    padded = np.pad(binary, r, mode="constant", constant_values=0)
    # 零拷贝视图 (H, W, k, k)：每个像素一张 k×k 小表（同 io_crop_filter 手写滤波）
    windows = sliding_window_view(padded, (ksize, ksize))
    # 每张小表压成一个数（取最小）；axis=(-2,-1)：-1=小表的列、-2=小表的行
    return (windows.min(axis=(-2, -1))).astype(np.uint8)


def dilate_manual(binary: np.ndarray, ksize: int = 3) -> np.ndarray:
    """手写膨胀 = 最大值滤波（窗口有一个白就白）：每个像素换成它 k×k 邻域里的最大值。

    白=255、黑=0，所以"框里有一个白，中心就变白"——黑区被白啃掉一圈、白区向外长
    胖：ksize=3（半径 1）一次胖 1 像素，比窗口小的黑洞被整个填掉（镜像：腐蚀里比
    窗口小的白点直接消失）。与 erode_manual 逐行相同，只差最后 min -> max。

    ★ 一维手算（把图当成 1 行；窗口 = 自己 + 左右各 1 个）：
        原始中间 1 个白: [0, 0, 255, 0, 0]
        两边各补 1 个 0: [0, 0, 0, 255, 0, 0, 0]
        5 张窗口取 max（框里有 255 就是 255，全黑才 0）：
          [0,0,0] -> 0   [0,0,255] -> 255   [0,255,0] -> 255
          [255,0,0] -> 255   [0,0,0] -> 0
        结果 [0, 255, 255, 255, 0]：白点胖成 3 个（两端各胖 1）；输出仍是 5 个数
        （补 2 个后 7 个数里 3 窗口只能摆 7-3+1 = 5 个位置）。腐蚀是"4 个白缩成
        2 个"，这里"1 个白胖成 3 个"，刚好镜像。

      2D 就是放大版：窗口 3×3 = 9 个数（自己 + 周围一圈）。demo 实测：30×30 白方块
      （900 px）-> 32×32（1024 px），四边各胖 1。

    ★ 和 cv2.dilate 连边界都一致（实测：贴边白块全图逐像素相同，最大差 0），不需要
      像腐蚀那样只对拍内部。原因：补的 0 在取 max 时永远竞争不过任何像素（0 是下
      界），"补了等于没补"，恰好等价于 cv2 默认的"图外不参与"；而腐蚀取 min 时 0
      最有话语权（= 图外当黑），所以那边只有内部一致。

    定位：本质 = 对黑色的腐蚀（实测 dilate(x) == 255 - erode(255 - x)）；排序统计
    滤波家族三兄弟之一（取最小/正中/最大 = 腐蚀/中值/膨胀）；闭运算的前半段（粘合：
    缝宽 ≤ 2r 的两块连成一片，主仓库 eval 的 MORPH_CLOSE(15,15) 粘碎片靠它）、开运
    算的后半段（复原）。手写意义同腐蚀：对拍通过后放心用 cv2.dilate。
    """
    r = ksize // 2                       # 邻域半径 r：ksize=3 -> r=1，看自己 ±1 一圈
    # 图外补 r 圈 0：补出完整邻域；取 max 时 0 永远竞争不过，等于"图外不参与"
    padded = np.pad(binary, r, mode="constant", constant_values=0)
    # 零拷贝视图 (H, W, k, k)：每个像素一张 k×k 小表（同 erode_manual）
    windows = sliding_window_view(padded, (ksize, ksize))
    # 每张小表压成一个数（取最大）；axis=(-2,-1)：-1=小表的列、-2=小表的行
    return (windows.max(axis=(-2, -1))).astype(np.uint8)


def erode(binary, ksize=3):
    kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (ksize, ksize))
    return cv2.erode(binary, kernel)


def dilate(binary, ksize=3):
    kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (ksize, ksize))
    return cv2.dilate(binary, kernel)


def morph_open(binary: np.ndarray, ksize: int = 3) -> np.ndarray:
    """开运算（MORPH_OPEN）= "先腐蚀、再膨胀"打包成一步：去小白点、保大块。

    净效果：删掉所有"塞不下结构元"的白结构（孤立小点、细线、细桥、毛刺），
    塞得下的大块原样——与闭运算（morph_close）正好把顺序反过来。实测等价于
    dilate(erode(...))（本文件两个 wrapper）。生死由腐蚀决定，膨胀只负责复原
    外形——下面两例的矩阵看得最直白。

    ★ 例1 去小白点（1px 孤立点 + 3×3 块；#=白，.=黑）：
        原图(10 白)     腐蚀后(第1步)    再膨胀(第2步=open)
        ........        ........         ........
        .#...... <-点   ........         ........ <- 点没了
        ........        ........         ........
        ........        ........         ........
        ....###.        ........         ....###.
        ....###.        .....#.. <-块心  ....###.
        ....###.        ........         ....###.
        ........        ........         ........
      点死在腐蚀那一步（1px 点没有一格能塞下 3×3，被整个销毁）；膨胀只能从幸存
      者往外长，点没有种子。净效果 10 -> 9：块逐格复原（中间那步它缩成 1 px）。

    ★ 例2 切桥（两块 3×3 之间 1 条 1px 的桥）：
        原图(19 白)     腐蚀后(第1步)    再膨胀(第2步=open)
        .........       .........        .........
        .........       .........        .........
        .###.###.       .........        .###.###.
        .#######. <-桥  ..#...#.. <-块心 .###.###. <- 桥没了
        .###.###.       .........        .###.###.
        .........       .........        .........
        .........       .........        .........
      桥在腐蚀那一步被整个销毁（1px 宽的桥每格邻域都含黑）；两块各缩成一个"块心"，
      膨胀再逐格长回原块——桥没有种子，回不来。净效果 19 -> 18：两块复原、连接断开。

    ★ 判据是"形状塞得下结构元"，不是面积——ksize=3 实测：1×1、2×2 块 -> 0 px；
      3×3 -> 9 px、4×4 -> 16 px 原样；1px 宽的细桥/毛刺无论多长都必死。尾巴：白块
      里的洞离边缘太近会被开出缺口（腐蚀时洞与块外的黑连通、膨胀补不回）：留 1/2
      行白 -> 96->94/92，留 ≥3 行才原样。

    定位：主仓库 eval 输出二值 mask 后先开（清噪点、削毛刺——毛刺和大块同属一个
    组件，面积过滤删不掉）再闭（MORPH_CLOSE(15,15) 粘碎片）。开运算幂等：开两遍
    = 开一遍。
    """
    kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (ksize, ksize))
    # MORPH_OPEN 内部就是 erode 一遍再 dilate 一遍（等价 dilate(erode(x, k), k)）
    return cv2.morphologyEx(binary, cv2.MORPH_OPEN, kernel)


def morph_close(binary: np.ndarray, ksize: int = 3) -> np.ndarray:
    """闭运算（MORPH_CLOSE）= "先膨胀、再腐蚀"打包成一步：填小黑洞、保大块。

    净效果：填掉所有"塞不下结构元"的黑结构（小洞、细缝），大块原样——与开运算
    （morph_open）正好把顺序反过来。实测等价于 erode(dilate(...))（本文件两个
    wrapper）。生死由膨胀决定，腐蚀只负责复原外形——下面两例的矩阵看得最直白。

    ★ 例1 填洞（5×5 白块、中心 1 个洞；#=白，.=黑）：
        原图(24 白)     膨胀后(第1步)   再腐蚀(第2步=close)
        .......         #######         .......
        .#####.         #######         .#####.
        .#####.         #######         .#####.
        .##.##. <-洞    #######         .#####. <- 洞没了
        .#####.         #######         .#####.
        .#####.         #######         .#####.
        .......         .......         .......
      洞是在膨胀那一步被盖掉的（白胖一圈，洞没有幸存格）；腐蚀只能从白色外轮廓
      往里啃，洞里没有黑的种子可长。净效果 24 -> 25，外轮廓逐格不变。

    ★ 例2 粘缝（两块 2×2、中间 1px 黑缝）：
        原图(8 白)      膨胀后(第1步)   再腐蚀(第2步=close)
        .......         #######         .......
        .##.##. <-缝    #######         .#####. <- 缝没了
        .##.##.         #######         .#####.
        .......         .......         .......
      缝被膨胀那一步两边同时盖掉；腐蚀缩回外形后，缝已在白色区域内部、不在轮廓
      上，够不着。净效果 8 -> 10，两块外边缘（第 2、6 列）不变。

    ★ 判据（与 open 镜像）：洞/缝能塞下结构元就活，塞不下被填死——3×3 核实测：
      1×1、2×2 洞填上，3×3、4×4 洞原样（3×3 洞要 5×5 核才填得上）；缝宽 ≤ 2r
      被粘合（gap 1、2 粘上，gap 3 粘不上）。孤立白点过 close 原样保留（1 -> 1，
      删白点是 open 的活）、洞过 open 不会被填——各管各的。

    定位：主仓库 eval 输出二值 mask 后用 MORPH_CLOSE(15,15) 粘碎片——阈值化后
    碎成几块的检测连成一片，连通域统计才不会把同一个缺陷数成好几个。闭运算幂等
    （闭两遍 = 闭一遍）。
    """
    kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (ksize, ksize))
    # MORPH_CLOSE 内部就是 dilate 一遍再 erode 一遍（等价 erode(dilate(x, k), k)）
    return cv2.morphologyEx(binary, cv2.MORPH_CLOSE, kernel)


def rect_struct_element(ksize: int = 3) -> np.ndarray:
    """结构元：决定"拿什么形状的窗口去腐蚀/膨胀"。矩形全 1 最常用；
    椭圆核（MORPH_ELLIPSE）边缘更圆滑，仓库无监督 eval 用的就是椭圆核(15,15)。"""
    return cv2.getStructuringElement(cv2.MORPH_RECT, (ksize, ksize))


